import { prisma } from "../src/app/lib/prisma.js";
// import { fstat } from "fs"
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

async function main() {
  const allClasses = new Set();
  const classAttrRegex = /class(?:Name)?="([^"]+)"/g;

  // 1) Scan page.html for classes typed directly in Monaco-edited HTML
  const pages = await prisma.page.findMany({
    select: { html: true, jsxCode: true },
  });

  for (const p of pages) {
    for (const field of [p.html, p.jsxCode]) {
      if (!field) continue;
      let match;
      while ((match = classAttrRegex.exec(field)) !== null) {
        match[1].split(/\s+/).forEach((c) => c && allClasses.add(c));
      }
    }
  }

  // 2) Scan PageElementOverride.classes — space-separated class strings,
  //    NOT wrapped in class="..." so no regex needed, just split directly
  const overrides = await prisma.pageElementOverride.findMany({
    select: { classes: true },
  });

  for (const o of overrides) {
    if (!o.classes) continue;
    o.classes.split(/\s+/).forEach((c) => c && allClasses.add(c));
  }

  // Write to a scan file Tailwind's `content` array already points to
  const outPath = path.join(
    __dirname,
    "..",
    "src",
    "tailwind-cms-content.html",
  );
  const html =
    `<!-- AUTO-GENERATED by scripts/extract-cms-classes.js — DO NOT EDIT -->\n` +
    [...allClasses].map((c) => `<div class="${c}"></div>`).join("\n");

  fs.writeFileSync(outPath, html);
  console.log(`✅ Extracted ${allClasses.size} unique classes → ${outPath}`);
}

main()
  .catch((err) => {
    console.error("❌ extract-cms-classes failed:", err);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
